#include <iostream>
using namespace std;

int main() {
    int a, b;

    cin >> a >> b ;

    int sum = a + b;
    int product = a * b;

    cout << "Sum of " << a << " and " << b << " is: " << sum << endl;
    cout << "Product of " << a << " and " << b << " is: " << product << endl;
    return 0;
}